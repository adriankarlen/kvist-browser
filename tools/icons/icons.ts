import { readFileSync } from "node:fs";
import { join } from "node:path";
import { ICON_ROLES } from "../../src/shared/icons/roles.ts";

interface IconSpec {
  readonly lucide: string;
  readonly fill?: boolean;
}

export const OUTPUT = "src/shared/styles/icons.css";

/** Lucide ships each icon as a pretty-printed file with a licence comment and a class. */
function minify(svg: string, fill: boolean): string {
  const compact = svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+class="[^"]*"/g, "")
    .replace(/\s+(?:width|height)="24"/g, "")
    .replace(/\s+/g, " ")
    .replace(/>\s+</g, "><")
    .replace(/\s*\/>/g, "/>")
    .replace(/\s*>/g, ">")
    .trim();

  return fill ? compact.replace('fill="none"', 'fill="currentColor"') : compact;
}

/**
 * A data URI that survives a stylesheet: double quotes become single ones, so
 * the URI can sit in `url("…")`. Semicolons and braces are escaped too, because
 * the token tests split declarations on them.
 */
const dataUri = (svg: string): string =>
  `data:image/svg+xml,${svg.replaceAll('"', "'").replace(/[%#<>;{}]/g, (c) => encodeURIComponent(c))}`;

/** The stylesheet that carries every icon role as a token, from Lucide's own files. */
export function renderIconsCss(root: string): string {
  const lucide = join(root, "node_modules/lucide-static");

  const readIcon = (name: string): string =>
    readFileSync(join(lucide, "icons", `${name}.svg`), "utf8");

  const { version } = JSON.parse(readFileSync(join(lucide, "package.json"), "utf8"));

  const roles: ReadonlyArray<[string, IconSpec]> = Object.entries(ICON_ROLES);

  const lines = roles.map(
    ([role, { lucide: name, fill = false }]) =>
      `    --kv-icon-${role}: url("${dataUri(minify(readIcon(name), fill))}");`,
  );

  return [
    "/*",
    ` * @license Icons from Lucide ${version} (https://lucide.dev), ISC License.`,
    " * Copyright (c) 2026 Lucide Icons and Contributors. Permission to use, copy,",
    " * modify, and/or distribute this software for any purpose with or without fee",
    " * is hereby granted, provided that the above copyright notice and this",
    " * permission notice appear in all copies.",
    " *",
    " * Generated by tools/icons/generate.ts from src/shared/icons/roles.ts. Run",
    " * `pnpm icons` after changing the roles; do not edit this file by hand.",
    " */",
    "@layer kvist.tokens {",
    "  :root {",
    ...lines,
    "  }",
    "}",
    "",
  ].join("\n");
}
